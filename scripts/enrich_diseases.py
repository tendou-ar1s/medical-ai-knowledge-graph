def fix_name(name: str) -> str:
    return NAME_FIX.get(name, name)


def build_prevalence(node):
    """优先用 Open Targets 的关联靶点数作为「研究热度」指标"""
    # Open Targets 的总关联靶点数（totalAssoc）
    t = node.get("totalAssoc") or 0
    if t >= 10000:
        research = "研究热度极高"
    elif t >= 6000:
        research = "研究热度高"
    elif t >= 3000:
        research = "研究热度中等"
    elif t > 0:
        research = "研究热度较低"
    else:
        research = None
    return research


def main():
    base = os.path.dirname(__file__)
    src = os.path.join(base, "..", "src", "data", "graph-data.js")

    with open(src, "r", encoding="utf-8") as f:
        raw = f.read()

    start = raw.index("const GRAPH_DATA = ") + len("const GRAPH_DATA = ")
    end = raw.index(";\n\nwindow.GRAPH_DATA")
    data = json.loads(raw[start:end])

    matched = 0
    unmatched = []

    for n in data["nodes"]:
        if n["type"] != "disease":
            continue

        # 0) 修正英文名 -> 中文名
        raw_name = n["name"]
        n["name"] = fix_name(raw_name)
        name = n["name"]

        # 1) 中文概述（优先 zh 表，其次 extra 表）
        zh = ZH_DESC.get(name) or EXTRA_DESC.get(name)
        if zh:
            n["descZh"] = zh
            matched += 1
        else:
            unmatched.append(name)
            # 兜底：把英文描述换成通用中文说明
            n["descZh"] = f"{name}是一种需要专业诊断与规范治疗的疾病。点击可查看其关联的基因与分子靶点。"

        # 2) 分类
        n["category"] = classify(name)

        # 3) 流行程度：系统分布 + 研究热度
        cat_prev = PREVALENCE_BY_CATEGORY.get(n["category"], "常见")
        research = build_prevalence(n)
        n["prevalence"] = f"{cat_prev}；{research}" if research else cat_prev

        # 4) 清掉原始英文长描述（改为可选，减小文件）
        if n.get("desc") and len(n["desc"]) > 200:
            n["descEn"] = n["desc"][:400]
            del n["desc"]

    print(f"中文概述匹配: {matched} / {matched + len(unmatched)}")
    if unmatched:
        print(f"未匹配（使用兜底文案）: {len(unmatched)} 个")
        print("  例:", ", ".join(unmatched[:10]))

    # 统计分类分布
    cats = {}
    for n in data["nodes"]:
        if n["type"] == "disease":
            cats[n["category"]] = cats.get(n["category"], 0) + 1
    print("\n=== 疾病分类分布 ===")
    for k, v in sorted(cats.items(), key=lambda x: -x[1]):
        print(f"  {k:12} {v:3} 种")

    out = "// 数据来源：Open Targets Platform (https://platform.opentargets.org)\n"
    out += "// 自动生成，请勿手工编辑。重新生成：python scripts/convert_data.py\n"
    out += "// 布局：静态环形（按疾病系统分区），坐标已预计算\n"
    out += "const GRAPH_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    out += ";\n\nwindow.GRAPH_DATA = GRAPH_DATA;\n"

    with open(src, "w", encoding="utf-8") as f:
        f.write(out)

    print(f"\n输出: {src}  ({os.path.getsize(src)/1024:.1f} KB)")


if __name__ == "__main__":
    main()
